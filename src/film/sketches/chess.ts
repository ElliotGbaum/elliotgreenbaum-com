/**
 * THERE IS NO INDEX FINGER UP THE CHEEK, AND THERE MUST NOT BE.
 *
 * There was one for three passes: a long thin closed element standing on the
 * knuckles with a rounded tip, running up past the mouth. On paper it is the
 * most legible hand-mark available at this size — a thing that POINTS, crossing
 * the jaw, which says the hand is in front rather than merely touching.
 *
 * In this drawing it was a CHESS PIECE. A small closed shape with a domed top,
 * held upright in a fist, a few inches from the face, in a picture that has a
 * chessboard in it — the eye has no reason to read anything else, and nobody
 * who saw it read a finger. Worse, it turned the pose from thinking into
 * fiddling: the boy was holding a pawn up and looking at it, which is a
 * completely different and much less interesting thing to be doing.
 *
 * With it gone the chin simply rests in the dip in the knuckles, which is the
 * pose, and the gap in the contour still does the occluding.
 */

/** the chest, in front of the spine and behind the arm. The triangle of air it
 *  leaves between itself, the forearm and the table IS the pose — closed up,
 *  the arm merges into the body and the gesture is gone. */
const CHEST = hand(
  curve(W.edge, [
    [0.269, 0.687],
    [0.287, 0.717],
    [0.29, 0.762],
    [0.283, TOP],
  ]),
  0.003,
  7.4,
)

const STROKES: SketchStroke[] = [
  /* ---- the head, complete, in five marks ---- */
  ...BOY.slice(0, 6),

  /* ---- the pose. The table lands before the arm, so the elbow has something
     to rest on the moment it arrives. ---- */
  poly(W.edge, [
    [L, 0.9],
    [L, TOP],
    [R, TOP],
    [R, 0.9],
  ]),
  ...BOY.slice(6),
  ARM,
  CHEST,

  /* ---- and the front face of the table ---- */
  poly(W.line, [
    [L, 0.9],
    [R, 0.9],
  ]),

  /* ---- the board, last, and the men on it last of all ---- */
  ...BOARD,
  ...PAWN,
  ...KNIGHT,
]

export const CHESS: SketchData = fit(STROKES)
